import { expect, test } from '@playwright/test'
test('model search, real pointer drag, explicit save and selective undo UI', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page).toHaveTitle('Codex Model Picker')
  await expect(page.getByText('DEV · dữ liệu minh họa')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Lưu mặc định' })).toBeDisabled()
  await page.getByRole('combobox', { name: 'Model', exact: true }).click()
  await page.getByRole('textbox', { name: 'Tìm model' }).fill('5.4')
  await page.getByRole('option', { name: /GPT-5.4/ }).click()
  const slider = page.getByRole('slider', { name: 'Mức suy luận' })
  const box = await slider.boundingBox(); expect(box).not.toBeNull()
  const track = page.locator('.slider').first(), bounds = await track.boundingBox()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down(); await page.mouse.move(bounds!.x + bounds!.width * 2 / 3, box!.y + box!.height / 2, { steps: 10 }); await page.mouse.up()
  await expect(slider).toHaveAttribute('aria-valuetext', 'High')
  await expect(page.locator('.current-model')).toHaveText('gpt-5.3-codex')
  await page.getByRole('button', { name: 'Lưu mặc định' }).click()
  await expect(page.getByText('Đã lưu cấu hình mặc định', { exact: true })).toBeVisible()
  await expect(page.locator('.current-model')).toHaveText('gpt-5.4')
  await page.getByRole('button', { name: 'Lịch sử / Hoàn tác' }).click()
  await page.getByRole('button', { name: 'Hoàn tác', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Xác nhận hoàn tác' })).toBeVisible()
  await page.getByRole('button', { name: 'Xác nhận hoàn tác' }).click()
  await expect(page.locator('.current-model')).toHaveText('gpt-5.3-codex')
  expect(errors).toEqual([])
})

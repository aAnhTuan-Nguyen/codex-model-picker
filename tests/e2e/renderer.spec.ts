import { expect, test, type Locator, type Page } from '@playwright/test'

async function dragToHigh(page: Page, slider: Locator) {
  await slider.scrollIntoViewIfNeeded()
  await slider.focus()
  await page.keyboard.press('Home')
  const box = await slider.boundingBox()
  const bounds = await page.locator('.slider').filter({ has: slider }).boundingBox()
  expect(box).not.toBeNull()
  expect(bounds).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + bounds!.width * 2 / Number(await slider.getAttribute('aria-valuemax')), box!.y + box!.height / 2, { steps: 10 })
  await page.mouse.up()
  await expect(slider).toHaveAttribute('aria-valuetext', 'High')
}

test('independent agents, context, pointer sliders, explicit save and undo', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page).toHaveTitle('Codex Model Picker')
  await expect(page.getByText(/DEV ·/)).toBeVisible()
  const main = page.getByRole('combobox', { name: 'Model chính', exact: true })
  const child = page.getByRole('combobox', { name: 'Model subagent', exact: true })
  const context = page.getByRole('group', { name: 'Context window', exact: true })
  const save = page.getByRole('button', { name: 'Lưu mặc định', exact: true })
  await expect(main).toContainText('GPT-6 Astra')
  const initialChild = await child.innerText()
  const initialContext = await context.locator('input:checked').inputValue()
  const initialMainEffort = await page.getByRole('slider', { name: 'Mức suy luận', exact: true }).getAttribute('aria-valuetext')
  const initialChildEffort = await page.getByRole('slider', { name: 'Mức suy luận subagent', exact: true }).getAttribute('aria-valuetext')
  await expect(save).toBeDisabled()
  await expect(context.getByRole('radio', { name: '1M', exact: true })).toHaveCount(0)

  await child.click()
  await page.getByRole('textbox', { name: 'Tìm model subagent', exact: true }).fill('Sol')
  await page.getByRole('option', { name: /GPT-6.1 Sol/ }).click()
  await expect(child).toContainText('GPT-6.1 Sol')
  await expect(main).toContainText('GPT-6 Astra')
  await context.getByRole('radio', { name: '500K', exact: true }).check()
  await dragToHigh(page, page.getByRole('slider', { name: 'Mức suy luận', exact: true }))
  await dragToHigh(page, page.getByRole('slider', { name: 'Mức suy luận subagent', exact: true }))
  await expect(save).toBeEnabled()
  await expect(page.getByText('Đã lưu cấu hình mặc định', { exact: true })).toHaveCount(0)
  await save.click()
  await expect(page.getByText('Đã lưu cấu hình mặc định', { exact: true })).toBeVisible()
  await expect(save).toBeDisabled()
  await expect(context.getByRole('radio', { name: '500K', exact: true })).toBeChecked()
  await expect(child).toContainText('GPT-6.1 Sol')

  await page.getByRole('button', { name: 'Lịch sử / Hoàn tác' }).click()
  await page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Xác nhận hoàn tác' })).toBeVisible()
  await page.getByRole('button', { name: 'Xác nhận hoàn tác', exact: true }).click()
  await expect(page.getByText('Đã hoàn tác các mục cấu hình', { exact: true })).toBeVisible()
  await expect(main).toContainText('GPT-6 Astra')
  await expect(child).toHaveText(initialChild)
  await expect(context.locator('input:checked')).toHaveValue(initialContext)
  await expect(page.getByRole('slider', { name: 'Mức suy luận', exact: true })).toHaveAttribute('aria-valuetext', initialMainEffort!)
  await expect(page.getByRole('slider', { name: 'Mức suy luận subagent', exact: true })).toHaveAttribute('aria-valuetext', initialChildEffort!)
  expect(errors).toEqual([])
})

test('advertised Ultra and Max remain distinct through the slider and explicit save', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Model subagent', exact: true }).click()
  await page.getByRole('option', { name: /GPT-6.1 Sol/ }).click()
  const slider = page.getByRole('slider', { name: 'Mức suy luận subagent', exact: true })
  await slider.scrollIntoViewIfNeeded()
  await slider.focus()
  await page.keyboard.press('End')
  await expect(slider).toHaveAttribute('aria-valuetext', 'Ultra')
  await page.keyboard.press('ArrowLeft')
  await expect(slider).toHaveAttribute('aria-valuetext', 'Max')
  await page.getByRole('button', { name: 'Lưu mặc định', exact: true }).click()
  await expect(page.getByText('Đã lưu cấu hình mặc định', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Tải lại', exact: true }).click()
  await expect(slider).toHaveAttribute('aria-valuetext', 'Max')
  await expect(page.locator('.main-panel').getByRole('button', { name: 'Max', exact: true })).toHaveCount(0)
  await expect(page.locator('.main-panel').getByRole('button', { name: 'Ultra', exact: true })).toHaveCount(0)
})

